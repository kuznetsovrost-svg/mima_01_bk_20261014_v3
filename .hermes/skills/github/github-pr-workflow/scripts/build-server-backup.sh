#!/usr/bin/env bash
# build-server-backup.sh
#
# Re-runnable server-state backup to a private GitHub repo, using
# gh release create for the tarball and Contents API for the index.
#
# Pattern, not a fixed tool: copy this file, edit the 4 variables in
# the "USER CONFIG" block, and run. The script is idempotent — each
# invocation produces a uniquely-stamped release; the repo can hold
# N of them.
#
# Tested on Ubuntu 24.04 with gh 2.45.0 and tar 1.34.
#
# Usage:
#   ./build-server-backup.sh
#
# Environment:
#   GITHUB_TOKEN  optional; gh will use its own auth if available
#
# See references/github-backup-store.md for the design rationale.

set -euo pipefail

# ─── USER CONFIG — edit these 4 lines for your environment ────────────

SOURCE_DIR="/root"                                    # what to back up
BACKUP_STAGING="/root/migration/mima_01_bk_archives"  # where archives + manifest go
REPO="kuznetsovrost-svg/mima_01_bk"                   # owner/repo on GitHub
EXCLUDE_FILE="/root/migration/mima_01_bk_archives/excludes-latest.txt"

# ─── DERIVED ─────────────────────────────────────────────────────────

STAMP="$(date -u +%Y%m%d-%H%M%S)"
ARC_NAME="mima_01_bk-root-${STAMP}.tar.gz"
ARC_PATH="${BACKUP_STAGING}/${ARC_NAME}"
SHA_PATH="${ARC_PATH}.sha256"
NOTES_PATH="${BACKUP_STAGING}/release-notes-${STAMP}.md"
MANIFEST_PATH="${BACKUP_STAGING}/MANIFEST-${STAMP}.md"
LOG_PATH="${BACKUP_STAGING}/build-${STAMP}.log"
TAG="backup-${STAMP}"

mkdir -p "${BACKUP_STAGING}"

# ─── 1. Write default excludes if missing ────────────────────────────
# Conservative defaults that drop secrets, runtime state, and
# regenerable caches. Override by editing the file and re-running.

if [ ! -f "${EXCLUDE_FILE}" ]; then
    cat > "${EXCLUDE_FILE}" <<'EOF'
# Generated by build-server-backup.sh — edit freely, this won't be overwritten
# unless you delete the file.

# Secrets & credentials
**/.ssh
**/.gnupg
**/.netrc
**/.config/gh
**/.gitconfig
.hermes/.env
.hermes/.env.*
.hermes/auth.json
.hermes/processes.json
.hermes/gateway.lock
.hermes/gateway.pid
.hermes/auth.lock
.hermes/state.db
.hermes/state.db-shm
.hermes/state.db-wal
.hermes/kanban.db
.hermes/kanban.db.init.lock
.hermes/sessions/*.json
.hermes/sessions/*.lock

# Runtime / regenerable
.hermes/logs
.hermes/bin
.hermes/node
.hermes/curator
.hermes/curator_state*
.hermes/cache
.hermes/image_cache
.hermes/images
.hermes/audio_cache
.hermes/pairing
.hermes/sandboxes
.hermes/hooks
.hermes/matrix_threads.json
.hermes/.hermes_history
.hermes/.skills_prompt_snapshot.json
.hermes/.update_check
.hermes/skills/.archive
.hermes/skills/.curator_*
.hermes/skills/.usage.json
.hermes/skills/.bundled_manifest
.hermes/provider_models_cache.json
.hermes/ollama_cloud_models_cache.json
.hermes/models_dev_cache.json
.hermes/cron/*.lock
.local/share/tirith
.npm
.cache
node_modules
__pycache__
*.bak
*.bak.*
*.tmp
*.swp

# Recursive: never include the staging dir itself
migration/mima_01_bk_archives
migration/mima_01_bk_stage_*
migration/build_backup.sh
EOF
    echo "Wrote default excludes to ${EXCLUDE_FILE}"
fi

# ─── 2. Build the archive ────────────────────────────────────────────

echo "=== build start: $(date -Iseconds) ===" | tee "${LOG_PATH}"

cd "${SOURCE_DIR}"
tar --exclude-from="${EXCLUDE_FILE}" \
    -czf "${ARC_PATH}" . 2>&1 | tee -a "${LOG_PATH}"

SIZE=$(stat -c%s "${ARC_PATH}")
echo "  archive: ${ARC_PATH}  (${SIZE} bytes)" | tee -a "${LOG_PATH}"
sha256sum "${ARC_PATH}" | tee "${SHA_PATH}" | tee -a "${LOG_PATH}"

# Sanity: verify the archive
tar -tzf "${ARC_PATH}" > /dev/null
echo "  integrity: OK" | tee -a "${LOG_PATH}"

FILE_COUNT=$(tar -tzf "${ARC_PATH}" | wc -l)
echo "  file count: ${FILE_COUNT}" | tee -a "${LOG_PATH}"

# ─── 3. Build the manifest ───────────────────────────────────────────

# Top-level breakdown
TOP_BREAKDOWN=$(tar -tzf "${ARC_PATH}" \
    | sed 's|^./||' \
    | awk -F/ '{print $1"/"$2}' | sort -u | head -40)

# .hermes/ subdir breakdown (only if archive has any .hermes entries)
HERMES_BREAKDOWN=""
if tar -tzf "${ARC_PATH}" | grep -q '^\./.hermes/'; then
    HERMES_BREAKDOWN=$(tar -tzf "${ARC_PATH}" \
        | grep '^\./.hermes/' \
        | sed 's|^./.hermes/||' \
        | awk -F/ '{print $1}' | sort | uniq -c | sort -rn | head -20)
fi

SHA=$(cut -d' ' -f1 "${SHA_PATH}")

cat > "${MANIFEST_PATH}" <<MANIFEST
# server backup manifest

- **Date:** $(date -u +%Y-%m-%d\ %H:%M:%S) UTC
- **Source:** ${SOURCE_DIR}
- **Archive:** \`${ARC_NAME}\`  (${SIZE} bytes / $(awk "BEGIN{printf \"%.2f\", ${SIZE}/1024/1024}") MB)
- **SHA256:** \`${SHA}\`
- **Files:** ${FILE_COUNT}
- **Excludes file:** \`$(basename "${EXCLUDE_FILE}")\`

## Top-level entries

\`\`\`
${TOP_BREAKDOWN}
\`\`\`

## .hermes/ breakdown

\`\`\`
${HERMES_BREAKDOWN:-"(no .hermes entries in this archive)"}
\`\`\`

## How to restore

\`\`\`bash
# verify
sha256sum -c ${ARC_NAME}.sha256

# preview
tar -tzf ${ARC_NAME} | less

# extract one file
tar -xzf ${ARC_NAME} path/to/file

# full restore (overwrites destination)
mkdir /restore && cd /restore
tar -xzf ${ARC_NAME}
\`\`\`
MANIFEST

# ─── 4. Build the release notes ──────────────────────────────────────

cat > "${NOTES_PATH}" <<NOTES
Server backup of ${SOURCE_DIR}.

Archive: \`${ARC_NAME}\`  ($(awk "BEGIN{printf \"%.2f\", ${SIZE}/1024/1024}") MB)
SHA256: \`${SHA}\`
Files: ${FILE_COUNT}
See \`MANIFEST-${STAMP}.md\` in main for the full index.
NOTES

# ─── 5. Ship: release + Contents API ────────────────────────────────

echo "=== uploading release ===" | tee -a "${LOG_PATH}"
gh release create "${TAG}" \
    "${ARC_PATH}#${ARC_NAME}" \
    "${SHA_PATH}#sha256" \
    --repo "${REPO}" \
    --title "Server backup ${STAMP}" \
    --notes-file "${NOTES_PATH}" \
    --target main 2>&1 | tee -a "${LOG_PATH}"

echo "=== pushing manifest + excludes to main ===" | tee -a "${LOG_PATH}"
MANIFEST_B64=$(base64 -w0 < "${MANIFEST_PATH}")
EXCLUDE_B64=$(base64 -w0 < "${EXCLUDE_FILE}")

# Manifest
printf '{"message":"backup %s: add manifest","content":"%s","branch":"main"}' \
    "${STAMP}" "${MANIFEST_B64}" > /tmp/put_manifest.json
gh api -X PUT "repos/${REPO}/contents/MANIFEST-${STAMP}.md" \
    --input /tmp/put_manifest.json 2>&1 | tail -3 | tee -a "${LOG_PATH}"
rm -f /tmp/put_manifest.json

# Excludes (stamped name for traceability; also keep excludes-latest.txt as alias)
printf '{"message":"backup %s: add excludes list","content":"%s","branch":"main"}' \
    "${STAMP}" "${EXCLUDE_B64}" > /tmp/put_excludes.json
gh api -X PUT "repos/${REPO}/contents/excludes-${STAMP}.txt" \
    --input /tmp/put_excludes.json 2>&1 | tail -3 | tee -a "${LOG_PATH}"
rm -f /tmp/put_excludes.json

# ─── 6. Verify via API ───────────────────────────────────────────────

echo "=== verifying ===" | tee -a "${LOG_PATH}"
gh api "repos/${REPO}/releases/tags/${TAG}" --jq \
    '"  release: \(.name)\n  url:    \(.html_url)\n  assets: \(.assets | length)"' \
    2>&1 | tee -a "${LOG_PATH}"
gh api "repos/${REPO}/releases/tags/${TAG}" --jq \
    '.assets[] | "    \(.name)  \(.size) bytes  state=\(.state)"' \
    2>&1 | tee -a "${LOG_PATH}"

echo "=== done: $(date -Iseconds) ===" | tee -a "${LOG_PATH}"

cat <<EOF

Backup complete. URLs:
  Release:  https://github.com/${REPO}/releases/tag/${TAG}
  Archive:  https://github.com/${REPO}/releases/download/${TAG}/${ARC_NAME}
  Manifest: https://github.com/${REPO}/blob/main/MANIFEST-${STAMP}.md
  Log:      ${LOG_PATH}
EOF
